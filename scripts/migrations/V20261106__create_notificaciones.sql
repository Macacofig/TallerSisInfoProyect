BEGIN;
CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante BIGINT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    tipo VARCHAR(64) NOT NULL CHECK (btrim(tipo) <> ''),
    titulo VARCHAR(160) NOT NULL CHECK (btrim(titulo) <> ''),
    mensaje TEXT NOT NULL CHECK (btrim(mensaje) <> ''),
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    referencia_tipo VARCHAR(40),
    referencia_id BIGINT,
    CONSTRAINT ck_notificaciones_referencia CHECK (
        (referencia_tipo IS NULL AND referencia_id IS NULL) OR
        (referencia_tipo IS NOT NULL AND btrim(referencia_tipo) <> ''
         AND referencia_id IS NOT NULL AND referencia_id > 0)
    )
);
CREATE INDEX idx_notificaciones_estudiante_fecha
    ON notificaciones (id_estudiante, fecha_creacion DESC, id DESC);
CREATE INDEX idx_notificaciones_estudiante_no_leidas
    ON notificaciones (id_estudiante) WHERE leida = FALSE;
-- El frontend usa exclusivamente la API Spring con JWT propio.
-- Sin políticas, RLS deniega el acceso de roles cliente de Supabase.
ALTER TABLE notificaciones ENABLE ROW LEVEL SECURITY;
COMMIT;
